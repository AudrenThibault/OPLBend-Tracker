"""Rasterise the tracker's monospace font into a C header.

  gen_font.py OUT.h

One cell size for every glyph (TK_CW x TK_CH pixels), 4-bit coverage, two pixels per byte
(high nibble first). Characters 32..126 come from IBM Plex Mono Medium (SIL OFL 1.1,
assets/fonts); 128.. are drawn here (see EXTRA).
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

CW, CH = 8, 12                       # cell: 30 columns x 20 rows on the 240 x 240 panel
FONT = Path(__file__).resolve().parents[1] / "assets" / "fonts" / "IBMPlexMono-Medium.ttf"


def fit_font():
    """the largest size whose advance fits the cell width"""
    best = None
    for tenth in range(80, 200):
        f = ImageFont.truetype(str(FONT), tenth / 10)
        if f.getlength("M") > CW + 0.05:
            break
        best = f
    return best


def glyph_text(font, ch):
    img = Image.new("L", (CW * 4, CH * 4), 0)
    d = ImageDraw.Draw(img)
    asc, desc = font.getmetrics()
    top = (CH - (asc + desc)) // 2
    d.text((CW, CH + top), ch, font=font, fill=255)
    return img.crop((CW, CH, CW * 2, CH * 2))


def glyph_drawn(code):
    """extra symbols, drawn on a 4x grid then reduced (antialiased)"""
    s = 4
    img = Image.new("L", (CW * s, CH * s), 0)
    d = ImageDraw.Draw(img)
    w, h = CW * s, CH * s
    if code == 128:      # middle dot: an empty field
        r = 1.1 * s
        d.ellipse((w / 2 - r, h / 2 - r, w / 2 + r, h / 2 + r), fill=150)
    elif code == 129:    # play triangle
        d.polygon([(1.5 * s, 2 * s), (1.5 * s, h - 2 * s), (w - 1.2 * s, h / 2)], fill=255)
    elif code == 130:    # full cell
        d.rectangle((0, 0, w, h), fill=255)
    elif code == 131:    # small square (a held / tied note)
        d.rectangle((2 * s, 4 * s, w - 2 * s, h - 4 * s), fill=255)
    elif code == 132:    # left half bar (meter)
        d.rectangle((0, 2 * s, w / 2, h - 2 * s), fill=255)
    elif code == 133:    # full bar (meter)
        d.rectangle((0, 2 * s, w, h - 2 * s), fill=255)
    return img.resize((CW, CH), Image.LANCZOS)


EXTRA = list(range(128, 134))


def main():
    out = Path(sys.argv[1])
    font = fit_font()
    codes = list(range(32, 127)) + EXTRA
    data = bytearray()
    for c in codes:
        g = glyph_text(font, chr(c)) if c < 127 else glyph_drawn(c)
        px = list(g.tobytes())
        for i in range(0, len(px), 2):
            a, b = px[i] >> 4, px[i + 1] >> 4
            data.append(a << 4 | b)
    per = CW * CH // 2
    lines = [f"/* generated by tools/gen_font.py from {FONT.name} (SIL OFL 1.1) */",
             "#pragma once",
             f"#define TK_CW {CW}u",
             f"#define TK_CH {CH}u",
             f"#define TK_GLYPH_BYTES {per}u",
             f"#define TK_FIRST 32u",
             f"#define TK_LAST {codes[-1]}u",
             "/* 32..126 then 127 is skipped: index = code - 32, codes >= 128 at index code - 33 */",
             f"static const uint8_t TK_FONT[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines.append("};")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"font: {font.size:.1f} px in {CW}x{CH} cells, {len(codes)} glyphs, {len(data)} B -> {out}")


if __name__ == "__main__":
    main()
