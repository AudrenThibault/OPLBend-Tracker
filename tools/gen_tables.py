"""Tables for the OPL-style engine (firmware/src/opl.c), written as a C header.

  gen_tables.py OUT.h

TK_LOGSIN / TK_EXP: the OPL's log-sine and exponent ROMs (the same formulas as the chip and Nuked-OPL3),
so the operators have the chip's precision steps. TK_INC: the phase increment of each 1/64 semitone in
octave 0 (MIDI notes 0..11) for a 32-bit phase at FS. TK_ENV_A / TK_ENV_D: the envelope steps per
4 samples for the 64 effective rates, from the OPL's attack and decay times.
"""
import math
import sys
from pathlib import Path

FS = 24_000_000 / 544               # the I2S frame rate (core.h FS)
ENV_DIV = 4                         # samples per envelope step (opl.c)


def main():
    out = Path(sys.argv[1])
    logsin = [round(-math.log2(math.sin((i + 0.5) * math.pi / 512)) * 256) for i in range(256)]
    exp = [round((2 ** (i / 256) - 1) * 1024) for i in range(256)]
    inc = []
    for p in range(768):            # octave 0: MIDI notes 0..11, 64 steps a semitone
        f = 440 * 2 ** ((p / 64 - 69) / 12)
        inc.append(round(f * 2 ** 32 / FS))

    def speed(e):                   # relative envelope speed of an effective rate (4 R + rof)
        return (4 + (e & 3)) << (e >> 2)
    env_a, env_d = [], []
    for e in range(64):
        if e < 4:                   # rate 0: the envelope never moves
            env_a.append(0)
            env_d.append(0)
            continue
        t_att = 2826.24e-3 * speed(4) / speed(e)        # seconds, 0 -> full
        t_dec = 39280.64e-3 * speed(4) / speed(e)       # seconds, 0 -> 96 dB
        steps_a = t_att * FS / ENV_DIV
        a = math.log(512) / steps_a
        env_a.append(0xFFFFFFFF if e >= 60 or a >= 1 else max(1, round(a * (1 << 20))))
        steps_d = t_dec * FS / ENV_DIV
        env_d.append(max(1, round(512 * 65536 / steps_d)))

    def arr(name, typ, vals, per=12):
        lines = [f"static const {typ} {name}[{len(vals)}] = {{"]
        for i in range(0, len(vals), per):
            lines.append("    " + ", ".join(f"{v}u" for v in vals[i:i + per]) + ",")
        lines.append("};")
        return lines
    lines = ["/* generated by tools/gen_tables.py */", "#pragma once"]
    lines += arr("TK_LOGSIN", "uint16_t", logsin)
    lines += arr("TK_EXP", "uint16_t", exp)
    lines += arr("TK_INC", "uint32_t", inc, 8)
    lines += arr("TK_ENV_A", "uint32_t", env_a, 8)
    lines += arr("TK_ENV_D", "uint32_t", env_d, 8)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"tables: logsin/exp 256, inc 768, env 64 -> {out}")


if __name__ == "__main__":
    main()
