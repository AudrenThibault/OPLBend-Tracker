//  La police du tracker, 5x7 points.
//
//  Elle remplace une police 3x5 qu'on affichait agrandie une fois et demie.
//  Trois points de large ne suffisent tout simplement pas a distinguer des
//  lettres : « SEL+DOWN BACK TO SONG » se lisait « SEL+DORRENE=REAHTBDSONG ».
//  L'agrandissement n'y pouvait rien — il grossissait l'illisible.
//
//  Cinq points de large donnent de vraies lettres. Chaque octet porte une
//  ligne du glyphe, sur ses cinq bits de poids faible, le bit 4 a gauche.
//  Les caracteres vont de l'espace (0x20) au souligne (0x5F) : le tracker
//  n'affiche que des majuscules, des chiffres et quelques signes.
// ============================================================================
