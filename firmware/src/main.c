extern uint32_t _data_start[], _data_end[], _data_load[], _bss_start[], _bss_end[];
extern uint32_t _pool_start[], _pool_end[], _rt_start[], _rt_end[], _rt_load[];
extern void (*__init_array_start[])(void), (*__init_array_end[])(void);
extern int main(void);                            /* the tracker (firmware/amber/main.cpp) */

void fm1_timer5_irq(void)                        /* 10 kHz: the key scan, the ms clock, USB at 2 kHz */
{
    static uint32_t sub, last, acc;
    uint32_t t0 = fm1_ticks();
    fm1_timer5_ack();
    fm1_input_tick();
    acc += t0 - last;
    last = t0;
    while (acc >= 1000u * FM1_TICKS_PER_US) {
        acc -= 1000u * FM1_TICKS_PER_US;
        fm1_ms++;
    }
    if (sub % 5u == 0u)
        usb_poll();
    if (++sub == 10u)
        sub = 0;
}
extern void isr_timer5(void);

/* ── System messages (UBOOT, UPDATE, CRASH) in the tracker's own 5x7 font, x2 ── */
/* ── System messages (UBOOT, UPDATE, CRASH) in the tracker's own 5x7 font (shown x2 like the rest) ── */
static void sys_texte(uint32_t x, uint32_t y, const char *s, u16 c)
{
    for (; *s; s++, x += 6u) {
        uint32_t ch = (uint8_t)*s, gy, gx;
        if (ch >= 'a' && ch <= 'z')
            ch -= 32u;
        if (ch < 0x20u || ch >= 0x60u)
            ch = '?';
        for (gy = 0; gy < MD_FONT_HT; gy++)
            for (gx = 0; gx < MD_FONT_W; gx++)
                if ((md_font[ch - 0x20u][gy] & (0x10u >> gx)) && x + gx < FM1_VUE_L_COMPACTE && y + gy < RG_ECRAN_H)
                    fm1_px((int)((y + gy) * RG_ECRAN_L + x + gx), c);
    }
}

static void sys_message(const char *l1, const char *l2, u16 fond)   /* the whole screen, at once */
{
    uint32_t i;
    for (i = 0; i < RG_ECRAN_L * RG_ECRAN_H; i++)
        fm1_px((int)i, fond);
    fm1_zoom(0);                                  /* (au milieu quel que soit le ZOOM : le tracker le remet ensuite) */
    fm1_traits(0, 0, 0, 0, 0, 0);                 /* (pas de fils de circuit bending sur ces messages) */
    fm1_vu_page();                                /* la fenetre a gauche */
    fm1_nom_page("");
    for (i = 1; i < 9u; i++)                      /* au milieu en hauteur : les rangees vides au-dessus gardees, */
        if (i != 7u)                              /* et celle entre les deux lignes */
            fm1_rangee_vide((int)i);
    sys_texte((FM1_VUE_L_COMPACTE - 6u * (uint32_t)strlen(l1)) / 2u, 7u * FM1_CELL_H, l1, RGB15(31, 31, 31));
    if (l2)
        sys_texte((FM1_VUE_L_COMPACTE - 6u * (uint32_t)strlen(l2)) / 2u, 9u * FM1_CELL_H, l2, RGB15(28, 24, 31));
    s_page_perdue = 1;                            /* le tracker redessinera sa page (fm1_page_perdue) */
    s_ecran_neuf = 1;
    montre();
    lcd_sync();
}

#include "fm1_splash.h"   /* generated by build.py (tools/splash.py) */

/* The boot screen: the patched-up OPL3 chip, straight to the panel, line by line
   (two RAM lines: one is filled while the other goes out by DMA). */
static void splash(void)
{
    static uint16_t ligne[2][240];
    uint32_t y, x, k = 0;
    for (y = 0; y < 240u; y++) {
        uint16_t *l = ligne[k];
        k ^= 1u;
        for (x = 0; x < 240u; x++) {
            const uint32_t c = SPLASH_PAL[SPLASH_IDX[y * 240u + x]];
            l[x] = (uint16_t)((c >> 8) | (c << 8));      /* (the panel takes the high byte first) */
        }
        lcd_blit(0, y, 240, 1, l);
    }
    lcd_sync();
    s_page_perdue = 1;                            /* the tracker draws its page over it */
    s_ecran_neuf = 1;
}

static void hexs(char *b, uint32_t v)
{
    uint32_t i;
    for (i = 0; i < 8u; i++)
        b[i] = HEX[(v >> (28u - 4u * i)) & 15u];
    b[8] = 0;
}

static void fm1_fault(const fm1_crash_t *c)
{
    char b[12];
    uint32_t t0;
    fm1_audio_stop();
    lcd_wake_now();
    hexs(b, c->pc);
    sys_message("CRASH", b, RGB15(20, 2, 4));
    t0 = fm1_ticks();
    while ((uint32_t)(fm1_ticks() - t0) < 4000u * 1000u * FM1_TICKS_PER_US)
        ;
    fm1_reboot();
}

static void fm1_fatal(const char *quoi)           /* exit(), abort(): show it, then restart */
{
    uint32_t t0;
    fm1_audio_stop();
    sys_message("STOPPED", quoi, RGB15(20, 2, 4));
    t0 = fm1_ticks();
    while ((uint32_t)(fm1_ticks() - t0) < 3000u * 1000u * FM1_TICKS_PER_US)
        fm1_wdt_feed();
    bootguard.pending = 0;
    fm1_reboot();
}

static void master_poll(void)
{
    static int32_t knob = -1;
    int32_t a = fm1_adc_read(FM1_ADC_MASTER);   /* 0..1023 */
    if (a < 0)
        return;
    knob = knob < 0 ? a * 16 : knob + (a * 16 - knob) / 8;
    {
        uint32_t k = (uint32_t)knob / 16u;      /* a square law, as Felucca's */
        master_vol = (uint8_t)((k * k) >> 12 > 255u ? 255u : (k * k) >> 12);
    }
}

static void flash_boot(void)
{
    uint32_t f = irq_save();
    flash_ok = FL_FAR(fl_jedec_ram)() == 0x856014u;   /* the expected 1 MiB part, else RAM only */
    irq_restore(f);
}

/* once a frame (swiWaitForVBlank): the FM-1's own duties, whatever the tracker is doing */
static void fm1_entretien(void)
{
    fm1_wdt_feed();
    usb_retry(fm1_ms);
    if (fm1_ms > 30000u && bootguard.pending) {     /* a crash or hang in the first 30 s counts */
        bootguard.pending = 0;
        bootguard.failed = 0;
    }
    master_poll();
    {   /* OCT- + OCT+ held 5 s: UBOOT (recovery / update); from 2 s a countdown over the whole screen */
        static uint32_t t0, shown;
        uint32_t both = (1u << FM1_B_OCTDN) | (1u << FM1_B_OCTUP);
        while ((fm1_in.buttons & both) == both) {
            uint32_t held = fm1_ms - t0;
            fm1_wdt_feed();
            if (held > 5000u) {
                fm1_audio_stop();
                sys_message("UBOOT", 0, RGB15(0, 0, 0));
                usb_detach();
                fm1_delay_ms(30);
                bootguard.pending = 0;          /* intentional reset: not a failed boot */
                fm1_enter_uboot();
            }
            if (held <= 2000u)
                break;
            {
                static char b[] = "UBOOT IN 5";
                b[9] = (char)('0' + (5000u - held + 999u) / 1000u);
                sys_message(b, "LET GO TO CANCEL", RGB15(0, 0, 0));
                shown = 1;
            }
            fm1_delay_ms(20);
        }
        if ((fm1_in.buttons & both) != both) {
            t0 = fm1_ms;
            if (shown) {                          /* the tracker's screen back */
                shown = 0;
                s_ecran_neuf = 1;
            }
        }
    }
#if FELUCCA_OTA
    tk_service();                                   /* songs sent from the Mac (compat/fm1_transfert.c) */
    ota_service();                                  /* M-UPGRADE handshake */
    if (usb.ota_req) {                              /* M-UPGRADE upgrade command */
        usb.ota_req = 0;
        if (flash_ok)
            ota_session();                          /* returns only if nothing was committed */
        s_ecran_neuf = 1;
    }
#endif
    if (usb.uboot_req) {                            /* SysEx F0 22 24 35 7D F7 from the host */
        fm1_audio_stop();
        sys_message("UBOOT (USB)", 0, RGB15(0, 0, 0));
        fm1_delay_ms(20);
        usb_detach();
        fm1_delay_ms(30);
        bootguard.pending = 0;
        fm1_enter_uboot();
    }
}

static void fm1_main(void)
{
    void (**c)(void);
    flash_boot();
#if FELUCCA_OTA
    if (flash_ok)
        ota_boot_cleanup();                           /* staging area left by an update */
#endif
    lcd_init();
    splash();                                     /* (OPLBEND TRACKER, the version: in the image) */
    fm1_input_init();
    fm1_adc_init();
    master_poll();
    opl3_reset();
    audio_init();
    usb_start();
    fm1_timer5_start(isr_timer5, 4);
    fm1_guard_lock_top();
    fm1_irq_enable_all();
    for (c = __init_array_start; c < __init_array_end; c++)
        (*c)();                                     /* the C++ side's static constructors */
    fm1_delay_ms(2500);                             /* (le temps de voir l'ecran d'accueil) */
    s_ecran_neuf = 1;
    main();
    fm1_fatal("MAIN RETURNED");
}

void fm1_cstart(void)
{
    uint32_t *s, *d, p3, src, wdt;
    fm1_time_init();
    fm1_reset_reason();
    p3 = fm1_boot.p3_rst;
    src = fm1_boot.rst_src;
    wdt = fm1_boot.wdt_con;
    fm1_wdt_arm(0x0D);
    if (bootguard.magic != BOOTGUARD_MAGIC) {
        bootguard.magic = BOOTGUARD_MAGIC;
        bootguard.failed = 0;
        bootguard.pending = 0;
    }
    if (bootguard.pending)
        bootguard.failed++;
    bootguard.pending = 1;
    if (bootguard.failed >= 2u) {
        bootguard.failed = 0;
        bootguard.pending = 0;
        fm1_enter_uboot();
    }
    fm1_irq_init();
    for (d = _bss_start; d < _bss_end; d++)
        *d = 0;
    for (d = _pool_start; d < _pool_end; d++)
        *d = 0;
    for (s = _data_load, d = _data_start; d < _data_end; s++, d++)
        *d = *s;
    for (s = _rt_load, d = _rt_start; d < _rt_end; s++, d++)
        *d = *s;                                /* flash driver code that must run from RAM */
    fm1_mailbox_clear();
    fm1_guard_enable(FM1_GUARD_STACK | FM1_GUARD_WRITE | FM1_GUARD_BUS | FM1_GUARD_PC);
    fm1_boot.p3_rst = (uint8_t)p3;
    fm1_boot.rst_src = src;
    fm1_boot.wdt_con = (uint8_t)wdt;
    fm1_main();
    for (;;)
        ;
}
